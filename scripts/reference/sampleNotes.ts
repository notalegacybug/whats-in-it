/**
 * Writes docs/reference-review-sample.md from public/reference.json so a person can spot-check the notes.
 *
 *   npm run reference:sample
 *
 * Section 1: every entry with a note or caveat, sorted by name.
 * Section 2: listed entries with no note, picked with a fixed seed so the file only changes when the data does.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import type { Listing, RefEntry, Reference } from '../../src/reference/types'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const SEED = 20261112
const UNNOTED_COUNT = 30

/** mulberry32: a tiny seeded PRNG, so the "random" pick is the same on every run and machine. */
function seededRandom(seed: number): () => number {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

const byName = (x: RefEntry, y: RefEntry) => x.name.localeCompare(y.name, 'en') || (x.id < y.id ? -1 : 1)

const PART_OF = 'Listed as part of:'

function listingLines(l: Listing): string[] {
  const parts = [l.source, l.classification, l.year === null ? 'year not given' : String(l.year)].join(' · ')
  if (!l.qualifier) return [`  - ${parts}`]
  // A "Listed as part of:" qualifier carries the source's full listing name, which says what form or route is covered.
  const detail = l.qualifier.startsWith(PART_OF)
    ? `full listing name: ${l.qualifier.slice(PART_OF.length).trim()}`
    : `qualifier: ${l.qualifier}`
  return [`  - ${parts}`, `    - ${detail}`]
}

function block(e: RefEntry): string {
  const lines = [`### ${e.name}`, '', `- **id:** \`${e.id}\``, '- **listings:**', ...e.listings.flatMap(listingLines)]
  if (e.listings.length === 0) lines.push('  - (none)')
  lines.push(
    `- **function / regulatory note (as the screen shows it):** ${e.functionNote ?? '(none)'}`,
    `- **note:** ${e.note ?? '(none)'}`,
    `- **caveat:** ${e.caveat ?? '(none)'}`,
    '',
  )
  return lines.join('\n')
}

function main(): void {
  const reference = JSON.parse(readFileSync(join(ROOT, 'public', 'reference.json'), 'utf8')) as Reference
  const noted = reference.entries.filter((e) => e.note || e.caveat).sort(byName)

  // Shuffle a stable (id-sorted) copy with the seeded PRNG, then take the first N.
  const unnoted = reference.entries.filter((e) => e.listings.length > 0 && !e.note && !e.caveat).sort((x, y) => (x.id < y.id ? -1 : 1))
  const random = seededRandom(SEED)
  for (let i = unnoted.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1))
    ;[unnoted[i], unnoted[j]] = [unnoted[j], unnoted[i]]
  }
  const picked = unnoted.slice(0, UNNOTED_COUNT).sort(byName)

  const out = [
    '# Reference review sample',
    '',
    `Generated by \`npm run reference:sample\` from \`public/reference.json\` (version ${reference.version}). ` +
      'Please read each entry below and check three things: is the note factually right, is it neutral (it should only say what the ' +
      'substance is and where it comes from or what it is used for, with no health claims), and is each caveat correct about the form ' +
      'or route of exposure the listing covers. The second section shows listed entries that have no note, so you can see what an ' +
      'un-noted listed result looks like.',
    '',
    `## Entries with a note or caveat (${noted.length})`,
    '',
    ...noted.map(block),
    `## Listed entries without a note (${picked.length} of ${unnoted.length}, seed ${SEED})`,
    '',
    'Please flag any entry here whose full listing name limits it to a form, grade, use or route (for example "technical grade" or "mists"), so it can get a caveat.',
    '',
    ...picked.map(block),
  ]
  mkdirSync(join(ROOT, 'docs'), { recursive: true })
  writeFileSync(join(ROOT, 'docs', 'reference-review-sample.md'), out.join('\n'))
  console.log(`Wrote docs/reference-review-sample.md: ${noted.length} noted entries, ${picked.length} un-noted listed entries.`)
}

main()
